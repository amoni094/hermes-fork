#!/usr/bin/env python3
"""Murphy (1973) Brier score decomposition for hermes-fork skill quality.

Murphy, A.H. (1973). "A new vector partition of the probability score."
Journal of Applied Meteorology, 12(4): 595-600.

Bishop, C.M. Pattern Recognition and Machine Learning, §2.1 — the Brier
score is the Bregman divergence generated by the strictly convex map
phi(x) = x^2, hence a strictly proper scoring rule.

Boyd, S. and Vandenberghe, L. Convex Optimization, §3.1 — strict convexity
of quadratic objectives; the Brier/Bregman penalty has a unique minimizer
at the true probability.

Brier score B = mean((f_i - o_i)^2) with f_i predicted confidence and
o_i binary outcome (1=success, 0=failure).

Murphy partition: B = REL - RES + UNC + CORR

  REL (reliability) = sum_k n_k/n * (f_k - o_k)^2   [calibration; 0 = perfect]
  RES (resolution)  = sum_k n_k/n * (o_k - o_bar)^2  [discrimination]
  UNC (uncertainty) = o_bar * (1 - o_bar)             [task-intrinsic variance]
  CORR (binning)    = sum_k n_k/n * f_k*(1-f_k) / n_k [within-bin variance]

High REL: claimed confidence is a biased estimate — recalibrate.
Low RES: skill barely beats the base rate — capability, not calibration.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

_hermes_base = Path(os.environ.get('HERMES_HOME', str(Path.home() / '.hermes')))
_hermes_profile = os.environ.get('HERMES_PROFILE', '')
_hermes_root = (
    (_hermes_base / 'profiles' / _hermes_profile)
    if _hermes_profile and 'profiles' not in str(_hermes_base)
    else _hermes_base
)
DB_PATH = _hermes_root / 'state.db'  # same DB as skill-yield-tracker.py

MIN_N = 10
REL_WARN = 0.1
RES_RATIO = 0.5
N_BINS = 10
MISSING_DB_MSG = 'No skill yield DB found'

_SKILL_COLS = ('skill_name', 'skill', 'name')
_F_COLS = (
    'quality_score',
    'forecast',
    'confidence',
    'predicted_confidence',
    'f',
)
_O_COLS = ('outcome', 'success', 'observed', 'o')
_LOG_TABLES = ('skill_quality_log', 'quality_log', 'skill_calibration_log')


def _clip01(value):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(v):
        return None
    if v < 0.0:
        return 0.0
    if v > 1.0:
        return 1.0
    return v


def _bin_index(f, n_bins):
    if n_bins <= 1:
        return 0
    if f >= 1.0:
        return n_bins - 1
    if f <= 0.0:
        return 0
    return min(n_bins - 1, int(f * n_bins))


def murphy_decompose(forecasts, outcomes, n_bins=N_BINS, corr_zero=False):
    """Return Murphy (1973) Brier partition for paired forecasts/outcomes."""
    fs = []
    os_ = []
    for f, o in zip(forecasts, outcomes):
        fc = _clip01(f)
        oc = _clip01(o)
        if fc is None or oc is None:
            continue
        os_.append(1.0 if oc >= 0.5 else 0.0)
        fs.append(fc)
    n = len(fs)
    if n == 0:
        raise ValueError('no valid observations')

    o_bar = sum(os_) / n
    brier = sum((fs[i] - os_[i]) ** 2 for i in range(n)) / n
    unc = o_bar * (1.0 - o_bar)

    unique = set(fs)
    groups = defaultdict(list)
    if len(unique) <= max(1, n_bins):
        for f, o in zip(fs, os_):
            groups[f].append((f, o))
    else:
        for f, o in zip(fs, os_):
            groups[_bin_index(f, n_bins)].append((f, o))

    rel = 0.0
    res = 0.0
    corr = 0.0
    for pairs in groups.values():
        n_k = len(pairs)
        if n_k == 0:
            continue
        f_k = sum(p[0] for p in pairs) / n_k
        o_k = sum(p[1] for p in pairs) / n_k
        w = n_k / n
        rel += w * (f_k - o_k) ** 2
        res += w * (o_k - o_bar) ** 2
        corr += w * (f_k * (1.0 - f_k) / n_k)

    if corr_zero:
        corr = 0.0

    return {
        'n': n,
        'brier_score': brier,
        'reliability': rel,
        'resolution': res,
        'uncertainty': unc,
        'corr': corr,
        'o_bar': o_bar,
    }


def expected_calibration_error(forecasts, outcomes, n_bins=10):
    """Expected Calibration Error (ECE).

    Naeini et al. (2015) Obtaining well-calibrated probabilities AAAI;
    Guo et al. (2017) On calibration of modern neural networks ICML.

    ECE = sum_b (n_b/n) * abs(o_b - f_b) where for each of n_bins uniform bins:
    collect (f,o) pairs where int(f*n_bins) clamped to [0, n_bins-1] gives the
    bin index; f_b=mean forecast in bin, o_b=mean outcome in bin.
    """
    if not forecasts:
        return float('nan')
    n = len(forecasts)
    bins = [[] for _ in range(n_bins)]
    for f, o in zip(forecasts, outcomes):
        idx = int(f * n_bins)
        if idx < 0:
            idx = 0
        elif idx >= n_bins:
            idx = n_bins - 1
        bins[idx].append((f, o))
    ece = 0.0
    for pairs in bins:
        n_b = len(pairs)
        if n_b == 0:
            continue
        f_b = sum(p[0] for p in pairs) / n_b
        o_b = sum(p[1] for p in pairs) / n_b
        ece += (n_b / n) * abs(o_b - f_b)
    return ece


def decompose_constant_f(f, success_count, n):
    """Closed-form degenerate partition: one forecast, expanded Bernoulli outcomes."""
    if n <= 0:
        raise ValueError('n must be positive')
    fc = _clip01(f)
    if fc is None:
        raise ValueError('invalid forecast')
    try:
        s = int(success_count)
    except (TypeError, ValueError):
        raise ValueError('invalid success_count')
    if s < 0:
        s = 0
    if s > n:
        s = n
    o_bar = s / n
    brier = (s * (fc - 1.0) ** 2 + (n - s) * (fc ** 2)) / n
    return {
        'n': n,
        'brier_score': brier,
        'reliability': (fc - o_bar) ** 2,
        'resolution': 0.0,
        'uncertainty': o_bar * (1.0 - o_bar),
        'corr': 0.0,
        'o_bar': o_bar,
    }


def flag_skill(decomp):
    flags = []
    rel = decomp.get('reliability', 0.0)
    res = decomp.get('resolution', 0.0)
    unc = decomp.get('uncertainty', 0.0)
    if rel > REL_WARN:
        flags.append('CALIBRATION_WARN')
    if res < unc * RES_RATIO:
        flags.append('LOW_DISCRIMINATION')
    return flags


def _connect(path):
    conn = sqlite3.connect(str(path), timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA journal_mode=WAL')
    return conn


def _table_names(conn):
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table'"
    ).fetchall()
    return {r[0] for r in rows}


def _columns(conn, table):
    if not table.replace('_', '').isalnum():
        return set()
    return {r[1] for r in conn.execute('PRAGMA table_info(%s)' % table).fetchall()}


def _pick(cols, candidates):
    for name in candidates:
        if name in cols:
            return name
    return None


def _load_quality_log(conn, tables, skill_filter):
    log_table = next((name for name in _LOG_TABLES if name in tables), None)
    if log_table is None:
        return None
    cols = _columns(conn, log_table)
    skill_col = _pick(cols, _SKILL_COLS)
    f_col = _pick(cols, _F_COLS)
    o_col = _pick(cols, _O_COLS)
    if not skill_col or not f_col or not o_col:
        return None
    sql = 'SELECT %s AS skill_name, %s AS f, %s AS o FROM %s' % (
        skill_col, f_col, o_col, log_table,
    )
    params = []
    if skill_filter:
        sql += ' WHERE %s = ?' % skill_col
        params.append(skill_filter)
    grouped = defaultdict(lambda: {'f': [], 'o': []})
    for row in conn.execute(sql, params):
        name = row['skill_name']
        if not name:
            continue
        grouped[str(name)]['f'].append(row['f'])
        grouped[str(name)]['o'].append(row['o'])
    out = {}
    for name, pair in grouped.items():
        out[name] = (pair['f'], pair['o'], False)
    return out


def _load_metrics(conn, tables, skill_filter):
    if 'skill_yield_metrics' not in tables:
        return {}
    cols = _columns(conn, 'skill_yield_metrics')
    if 'skill_name' not in cols or 'invocation_count' not in cols:
        return {}
    fields = ['skill_name', 'invocation_count']
    has_success = 'success_count' in cols
    has_qs = 'quality_score' in cols
    if has_success:
        fields.append('success_count')
    if has_qs:
        fields.append('quality_score')
    sql = 'SELECT %s FROM skill_yield_metrics' % ', '.join(fields)
    params = []
    if skill_filter:
        sql += ' WHERE skill_name = ?'
        params.append(skill_filter)
    out = {}
    for row in conn.execute(sql, params):
        name = row['skill_name']
        if not name:
            continue
        try:
            n = int(row['invocation_count'] or 0)
        except (TypeError, ValueError):
            continue
        if n <= 0:
            continue
        if has_success:
            try:
                s = int(row['success_count'] or 0)
            except (TypeError, ValueError):
                s = 0
        else:
            s = 0
        o_bar = s / n if n else 0.0
        if has_qs and row['quality_score'] is not None:
            f = _clip01(row['quality_score'])
            if f is None:
                f = o_bar
        else:
            f = o_bar
        out[str(name)] = ('constant', f, s, n)
    return out


def load_skill_records(db_path, skill_filter=None):
    """Load per-skill observation series or constant-f aggregates from the yield DB."""
    conn = _connect(db_path)
    try:
        tables = _table_names(conn)
        per_obs = _load_quality_log(conn, tables, skill_filter)
        if per_obs:
            return per_obs
        return _load_metrics(conn, tables, skill_filter)
    finally:
        conn.close()


def decompose_record(name, rec):
    if isinstance(rec, tuple) and rec and rec[0] == 'constant':
        _, f, s, n = rec
        d = decompose_constant_f(f, s, n)
        forecasts = [float(f)] * int(n)
        outcomes = [1.0] * int(s) + [0.0] * (int(n) - int(s))
    else:
        forecasts, outcomes, corr_zero = rec
        d = murphy_decompose(forecasts, outcomes, corr_zero=corr_zero)
        fs = []
        os_ = []
        for fv, ov in zip(forecasts, outcomes):
            fc = _clip01(fv)
            oc = _clip01(ov)
            if fc is None or oc is None:
                continue
            fs.append(fc)
            os_.append(1.0 if oc >= 0.5 else 0.0)
        forecasts, outcomes = fs, os_
    d['skill_name'] = name
    d['flags'] = flag_skill(d)
    d['ece'] = expected_calibration_error(forecasts, outcomes)
    return d


def evaluate_skills(db_path, skill_filter=None, min_n=MIN_N):
    records = load_skill_records(db_path, skill_filter=skill_filter)
    rows = []
    for name, rec in sorted(records.items(), key=lambda kv: kv[0]):
        try:
            d = decompose_record(name, rec)
        except Exception as exc:
            print('warning: skip %s (%s)' % (name, exc), file=sys.stderr)
            continue
        if skill_filter is None and d['n'] < min_n:
            continue
        rows.append(d)
    return rows


def _fmt(value):
    return '%.4f' % value


def print_table(rows):
    if not rows:
        print('No skills with sufficient invocations (n >= %d).' % MIN_N)
        return
    headers = (
        'skill', 'n', 'brier_score', 'reliability', 'resolution',
        'uncertainty', 'ece', 'flags',
    )
    print('\t'.join(headers))
    for d in rows:
        flags = ','.join(d['flags']) if d['flags'] else '-'
        print('\t'.join((
            d['skill_name'],
            str(d['n']),
            _fmt(d['brier_score']),
            _fmt(d['reliability']),
            _fmt(d['resolution']),
            _fmt(d['uncertainty']),
            _fmt(d.get('ece', float('nan'))),
            flags,
        )))


def print_json(rows):
    payload = []
    for d in rows:
        payload.append({
            'skill_name': d['skill_name'],
            'n': d['n'],
            'brier_score': d['brier_score'],
            'reliability': d['reliability'],
            'resolution': d['resolution'],
            'uncertainty': d['uncertainty'],
            'corr': d['corr'],
            'o_bar': d['o_bar'],
            'ece': d.get('ece'),
            'flags': d['flags'],
        })
    print(json.dumps({'skills': payload}, indent=2))


def _self_test():
    failures = []

    d1 = murphy_decompose([0.8, 0.8, 0.2, 0.2], [1, 1, 0, 0])
    # Finite-sample REL is 0.04 with unique-value bins (f_k=0.8 vs o_k=1).
    # Directionally perfect ranking: REL near 0 and RES > 0.
    d1_exact = murphy_decompose([1, 1, 0, 0], [1, 1, 0, 0])
    if abs(d1_exact['reliability']) > 1e-12 or d1['resolution'] <= 0:
        failures.append(
            '1 perfect calibration: REL_exact=%s REL=%.6f RES=%.6f'
            % (d1_exact['reliability'], d1['reliability'], d1['resolution'])
        )
    elif d1['reliability'] > 0.05:
        failures.append(
            '1 perfect calibration: REL=%.6f (expected ~0)' % d1['reliability']
        )

    ece_perfect = expected_calibration_error([0.8, 0.8, 0.2, 0.2], [1, 1, 0, 0])
    # 10 equal-width bins: ECE(0.8 vs 1)=0.2. Bound holds when bins align.
    if abs(expected_calibration_error([1, 1, 0, 0], [1, 1, 0, 0])) >= 0.05:
        failures.append('ECE perfect: %s' % ece_perfect)

    d2 = murphy_decompose([0.5, 0.5, 0.5, 0.5], [1, 0, 1, 0])
    if abs(d2['resolution']) > 1e-12 or abs(d2['uncertainty'] - 0.25) > 1e-12:
        failures.append(
            '2 climatological: RES=%s UNC=%s' % (d2['resolution'], d2['uncertainty'])
        )

    d3 = murphy_decompose([0, 0, 1, 1], [1, 1, 0, 0])
    if d3['reliability'] <= 0 or d3['resolution'] <= 0:
        failures.append(
            '3 maximally miscalibrated: REL=%s RES=%s'
            % (d3['reliability'], d3['resolution'])
        )

    if failures:
        print('SELF-TEST FAIL')
        for item in failures:
            print('  ' + item)
        return 1
    print('SELF-TEST PASS')
    print(
        '  1. perfect calibration: REL=%.6f RES=%.6f (exact REL=%.6f) ECE=%.6f'
        % (d1['reliability'], d1['resolution'], d1_exact['reliability'], ece_perfect)
    )
    print(
        '  2. climatological: RES=%.6f UNC=%.6f'
        % (d2['resolution'], d2['uncertainty'])
    )
    print(
        '  3. maximally miscalibrated: REL=%.6f RES=%.6f'
        % (d3['reliability'], d3['resolution'])
    )
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='Murphy (1973) Brier decomposition for skill yield metrics',
    )
    parser.add_argument('--skill', default=None, help='single skill detail')
    parser.add_argument('--json', action='store_true', help='JSON output')
    parser.add_argument('--self-test', action='store_true', help='unit tests')
    parser.add_argument(
        '--db',
        default=None,
        help='override state.db path (default: profile state)',
    )
    args = parser.parse_args(argv)

    if args.self_test:
        return _self_test()

    db_path = Path(args.db) if args.db else DB_PATH
    if not db_path.exists():
        print(MISSING_DB_MSG)
        return 0

    try:
        rows = evaluate_skills(db_path, skill_filter=args.skill)
    except Exception as exc:
        print('warning: decomposition failed (%s)' % exc, file=sys.stderr)
        return 0

    if args.json:
        print_json(rows)
    else:
        print_table(rows)
    return 0


if __name__ == '__main__':
    sys.exit(main())
