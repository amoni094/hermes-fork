#!/usr/bin/env python3
"""
spike-actuator.py — Build stub artifacts and layer1 demo tests from IMPLEMENT items.

Reads pending-improvements-report.json (produced by pending-improvements-review.py),
and for each IMPLEMENT item:
  1. Creates a minimal stub artifact at the appropriate path under spikes/
  2. Creates a runnable pytest stub in spikes/tests/test_<slug>.py
  3. Logs each action to spike-actuator-log.json

This closes the theory-to-practice gap: the pipeline discovers and scores improvements,
this script instantiates them as runnable code stubs ready for human or agent iteration.

Idempotent: existing stubs are skipped (use --force to overwrite).

Usage:
  python3 spike-actuator.py [--dry-run] [--force] [--profile PROFILE]

Output:
  ~/.hermes/profiles/fork/spikes/           — artifact stubs
  ~/.hermes/profiles/fork/spikes/tests/     — pytest layer1 demo tests
  ~/.hermes/profiles/fork/cache/spike-actuator-log.json
"""

import argparse
import hashlib
import json
import os
import re
import sys
from datetime import datetime, timezone, UTC
from pathlib import Path

HERMES_HOME    = Path(os.environ.get("HERMES_HOME", str(Path.home() / ".hermes")))
HERMES_PROFILE = os.environ.get("HERMES_PROFILE", "fork")

# A004-fix: use name-based unwrap to avoid exists() accepting ghost doubled dirs.
if HERMES_HOME.name == HERMES_PROFILE or str(HERMES_HOME).endswith(f"profiles/{HERMES_PROFILE}"):
    _profile_root = HERMES_HOME
else:
    _profile_root = HERMES_HOME / "profiles" / HERMES_PROFILE

REPORT_PATH = _profile_root / "cache" / "pending-improvements-report.json"
SPIKES_DIR  = _profile_root / "cache" / "research" / "spikes"
TESTS_DIR   = SPIKES_DIR / "tests"
LOG_PATH    = _profile_root / "cache" / "spike-actuator-log.json"
LAUNCH_PATH = _profile_root / "cache" / "launch-spike.json"


def _slug(title: str) -> str:
    """Convert title to a filesystem-safe slug."""
    s = re.sub(r"[^\w\s-]", "", title.lower())
    s = re.sub(r"[\s_]+", "-", s.strip())
    s = re.sub(r"-+", "-", s)
    return s[:48] or hashlib.md5(title.encode()).hexdigest()[:12]


def _parse_artifact(artifact: str) -> tuple[str, str]:
    """
    Parse 'artifact_type: name' into (artifact_type, name).
    Returns ('unknown', artifact) on parse failure.
    """
    for prefix in (
        "cron script:", "plugin hook:", "sqlite schema:", "json state file:",
        "skill document:", "subprocess helper:",
    ):
        if artifact.lower().startswith(prefix):
            name = artifact[len(prefix):].strip()
            return prefix.rstrip(":"), name
    # Try colon split
    if ":" in artifact:
        atype, name = artifact.split(":", 1)
        return atype.strip().lower(), name.strip()
    return "unknown", artifact.strip()


def _stub_path(atype: str, name: str) -> Path:
    """Map artifact type + name to a stub output path under spikes/."""
    safe = re.sub(r"[^\w.\-]", "_", name)
    if atype == "cron script":
        # Don't write to scripts/ — write a stub to spikes/ to avoid touching production
        return SPIKES_DIR / safe
    if atype == "plugin hook":
        # Extract plugin name from 'hook_name in plugin.py'
        m = re.search(r"in\s+(\S+)", name)
        plugin = m.group(1) if m else safe.replace(" ", "_")
        plugin_slug = re.sub(r"[^\w.\-]", "_", plugin)
        return SPIKES_DIR / f"{plugin_slug}-stub.py"
    if atype in ("sqlite schema", "sqlit schema"):
        # Extract table name from 'table_name in db.db'
        m = re.search(r"^(\w+)", name)
        table = m.group(1) if m else safe
        return SPIKES_DIR / f"{table}.sql"
    if atype == "json state file":
        n = safe if safe.endswith(".json") else safe + ".json.stub"
        return SPIKES_DIR / n
    if atype == "skill document":
        return SPIKES_DIR / f"{safe}-skill-stub.md"
    if atype == "subprocess helper":
        return SPIKES_DIR / safe
    return SPIKES_DIR / f"{safe}.stub"


def _write_py_stub(path: Path, item: dict) -> None:
    title      = item.get("title", "Untitled") or "Untitled"
    scaffold   = item.get("scaffold") or ""
    hard_core  = item.get("hard_core") or ""
    kill_test  = item.get("kill_test") or ""
    layer1     = item.get("layer1_demo") or ""
    hypothesis = item.get("hypothesis") or ""
    target     = item.get("target") or ""

    lines = [
        "#!/usr/bin/env python3",
        '"""',
        f"Spike stub: {title}",
        "",
        f"Target:    {target}",
        f"Scaffold:  {scaffold}",
        f"Invariant: {hard_core}",
        f"Kill test: {kill_test}",
        f"Hypothesis:{hypothesis}",
        "",
        f"Layer1 demo: {layer1}",
        '"""',
        "",
        "# TODO: IMPLEMENT — this stub was auto-generated by spike-actuator.py",
        "# Replace the pass below with a real implementation.",
        "",
        "",
        "def main():",
        "    pass",
        "",
        "",
        'if __name__ == "__main__":',
        "    main()",
        "",
    ]
    path.write_text("\n".join(lines))


def _write_sql_stub(path: Path, item: dict) -> None:
    title     = item.get("title", "Untitled")
    artifact  = item.get("artifact", "")
    hard_core = item.get("hard_core", "")

    # Extract table name
    m = re.search(r"^(\w+)", artifact.split(":", 1)[-1].strip())
    table = m.group(1) if m else "new_table"

    lines = [
        f"-- Spike stub: {title}",
        f"-- Invariant: {hard_core}",
        "-- TODO: IMPLEMENT — define columns",
        "",
        f"CREATE TABLE IF NOT EXISTS {table} (",
        "    id      INTEGER PRIMARY KEY,",
        "    created TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),",
        "    -- TODO: add columns",
        "    data    TEXT",
        ");",
        "",
    ]
    path.write_text("\n".join(lines))


def _write_md_stub(path: Path, item: dict) -> None:
    title      = item.get("title", "Untitled")
    scaffold   = item.get("scaffold", "")
    hard_core  = item.get("hard_core", "")
    kill_test  = item.get("kill_test", "")
    hypothesis = item.get("hypothesis", "")

    lines = [
        "---",
        f'title: "{title}"',
        f'scaffold: "{scaffold}"',
        f'invariant: "{hard_core}"',
        "status: stub",
        "---",
        "",
        f"# {title}",
        "",
        f"**Hypothesis:** {hypothesis}",
        "",
        f"**Kill test:** {kill_test}",
        "",
        "## TODO: IMPLEMENT",
        "",
        "Replace this stub with the full skill document.",
        "",
    ]
    path.write_text("\n".join(lines))


def _write_json_stub(path: Path, item: dict) -> None:
    """Write a minimal JSON state-file stub. B005-fix: json state files must not be Python."""
    title     = item.get("title", "Untitled")
    hard_core = item.get("hard_core") or ""
    scaffold  = item.get("scaffold") or ""
    stub = {
        "_stub":      True,
        "_generated": "spike-actuator.py",
        "title":      title,
        "schema_note": f"TODO: define schema. Invariant: {hard_core}. Scaffold: {scaffold}",
    }
    path.write_text(json.dumps(stub, indent=2) + "\n")


def _write_stub(path: Path, item: dict, atype: str) -> None:
    """Write a stub file appropriate for the artifact type."""
    if atype == "sqlite schema" or path.suffix == ".sql":
        _write_sql_stub(path, item)
    elif atype == "skill document" or path.suffix == ".md":
        _write_md_stub(path, item)
    elif atype == "json state file" or path.suffix in (".json", ".stub") and ".json" in path.name:
        _write_json_stub(path, item)
    else:
        _write_py_stub(path, item)


def _write_test(test_path: Path, item: dict, slug: str) -> None:
    title     = item.get("title", "Untitled")
    layer1    = item.get("layer1_demo", "")
    kill_test = item.get("kill_test", "")
    hard_core = item.get("hard_core", "")

    fn_name = re.sub(r"[^\w]", "_", slug)[:40]

    lines = [
        "# Auto-generated layer1 demo test — spike-actuator.py",
        f"# Title: {title}",
        f"# Invariant: {hard_core}",
        f"# Kill test: {kill_test}",
        "",
        "# Layer1 demo:",
        f"#   {layer1}",
        "",
        "# This test is a runnable stub. Replace the TODO assertion with a",
        "# real property check derived from layer1_demo above.",
        "",
        "",
        f"def test_layer1_{fn_name}():",
        f'    """Layer1 demo: {layer1[:120]}"""',
        "    # TODO: IMPLEMENT — wire up the real check",
        "    pass  # placeholder: replace with falsifiable assertion",
        "",
    ]
    test_path.write_text("\n".join(lines))



def _self_test() -> int:
    import tempfile, uuid, shutil as _sh
    td = Path(tempfile.mkdtemp(prefix=f"sa-{uuid.uuid4().hex[:8]}-"))
    try:
        report = {
            "implement": [
                {
                    "title": "Test Spike Item",
                    "artifact": "cron script: test-spike.py",
                    "target": "hermes-scripts/test-spike.py",
                    "change_type": "script",
                    "recommendation": "IMPLEMENT",
                }
            ]
        }
        rp = td / "pending-improvements-report.json"
        rp.write_text(json.dumps(report))
        items = _implement_items(report)
        assert len(items) == 1
        launch = _build_launch(items, rp)
        out = td / "launch-spike.json"
        tmp = out.with_suffix(".tmp")
        tmp.write_text(json.dumps(launch, indent=2))
        os.replace(str(tmp), str(out))
        data = json.loads(out.read_text())
        assert data["n_implement"] == 1
        assert data["items"][0]["title"] == "Test Spike Item"
        assert data["items"][0]["action"] == "implement"
        empty = _implement_items({})
        assert empty == []
        print("[spike-actuator] --self-test PASS")
        return 0
    finally:
        _sh.rmtree(td, ignore_errors=True)


def _implement_items(data) -> list:
    if not isinstance(data, dict):
        return []
    if "ranked" in data and isinstance(data["ranked"], list):
        return [item for item in data["ranked"] if item.get("recommendation") == "IMPLEMENT"]
    if "implement" in data and isinstance(data["implement"], list):
        return data["implement"]
    return []


def _build_launch(items: list, source: Path) -> dict:
    actionable = []
    for item in items:
        if not isinstance(item, dict):
            continue
        actionable.append({
            "title": item.get("title") or "",
            "target": item.get("target") or "",
            "artifact": item.get("artifact") or "",
            "change_type": item.get("change_type") or "script",
            "action": "implement",
            "governance_required": bool(item.get("governance_required", False)),
        })
    return {
        "ts": datetime.now(UTC).isoformat(),
        "source": str(source),
        "n_implement": len(actionable),
        "items": actionable,
    }


def process_item(item: dict, dry_run: bool, force: bool) -> dict:
    title    = item.get("title", "Untitled")
    artifact = (item.get("artifact") or "").strip()
    layer1   = (item.get("layer1_demo") or "").strip()
    slug     = _slug(title)

    log_entry = {
        "title":               title,
        "artifact":            artifact,
        "stub_path":           None,
        "test_path":           None,
        "status":              "skipped",
        "reason":              "",
        "change_type":         item.get("change_type", "script"),
        "governance_required": bool(item.get("governance_required", False)),
    }

    # Governance-required items (runtime / config) cannot be stub-created here;
    # they need a filed governance proposal. Log them as deferred so the pipeline
    # can count them separately from viable stubs.
    if item.get("governance_required"):
        log_entry["status"] = "governance-deferred"
        log_entry["reason"] = (
            f"change_type={item.get('change_type', '?')} requires governance proposal "
            f"before implementation. File via improvement_governance.py propose."
        )
        print(f"  [governance-deferred] {title[:70]} (change_type={item.get('change_type')})")
        return log_entry

    # ── Stub ─────────────────────────────────────────────────────────────────
    if artifact:
        atype, name = _parse_artifact(artifact)
        path = _stub_path(atype, name)
        log_entry["stub_path"] = str(path)

        if path.exists() and not force:
            log_entry["reason"] = f"stub already exists: {path}"
        elif dry_run:
            print(f"  [dry-run] would create stub: {path}")
            log_entry["status"] = "would-create"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            _write_stub(path, item, atype)
            print(f"  [stub] {path}")
            log_entry["status"] = "created"

    # ── Layer1 test ──────────────────────────────────────────────────────────
    if layer1:
        test_path = TESTS_DIR / f"test_{slug}.py"
        log_entry["test_path"] = str(test_path)

        if test_path.exists() and not force:
            if log_entry["status"] == "skipped":
                log_entry["reason"] = "test already exists (and no stub needed)"
        elif dry_run:
            print(f"  [dry-run] would create test: {test_path}")
            if log_entry["status"] not in ("created", "would-create"):
                log_entry["status"] = "would-create"
        else:
            test_path.parent.mkdir(parents=True, exist_ok=True)
            _write_test(test_path, item, slug)
            print(f"  [test]  {test_path}")
            if log_entry["status"] != "created":
                log_entry["status"] = "created"

    if log_entry["status"] == "skipped" and not log_entry["reason"]:
        log_entry["reason"] = "no artifact and no layer1_demo"

    return log_entry


def main() -> None:
    pa = argparse.ArgumentParser(description="Spike actuator: build stubs from IMPLEMENT items")
    pa.add_argument("--self-test", action="store_true", help="Run isolated self-test and exit")
    pa.add_argument("--dry-run", action="store_true", help="Print what would be created, create nothing")
    pa.add_argument("--force",   action="store_true", help="Overwrite existing stubs")
    pa.add_argument("--profile", default=HERMES_PROFILE, help="Hermes profile name")
    args = pa.parse_args()
    if args.self_test:
        sys.exit(_self_test())

    # B004-fix: re-derive paths from args.profile so --profile actually works.
    if args.profile and args.profile != HERMES_PROFILE:
        _hh = Path(os.environ.get("HERMES_HOME", str(Path.home() / ".hermes")))
        _p  = args.profile
        _pr = _hh if (_hh.name == _p or str(_hh).endswith(f"profiles/{_p}")) else _hh / "profiles" / _p
        _report_path = _pr / "cache" / "pending-improvements-report.json"
        _spikes_dir  = _pr / "spikes"
        _log_path    = _pr / "cache" / "spike-actuator-log.json"
    else:
        _report_path = REPORT_PATH
        _spikes_dir  = SPIKES_DIR
        _log_path    = LOG_PATH

    if not _report_path.exists():
        print(f"[spike-actuator] WARNING: report not found: {_report_path}")
        print("[spike-actuator] Nothing to actuate. Run pending-improvements-review.py first.")
        sys.exit(0)

    try:
        data = json.loads(_report_path.read_text())
    except Exception as exc:
        print(f"[spike-actuator] ERROR: cannot read report: {exc}")
        sys.exit(1)

    items = _implement_items(data)
    launch = _build_launch(items, _report_path)
    try:
        _lp = LAUNCH_PATH if args.profile == HERMES_PROFILE else (_report_path.parent / "launch-spike.json")
        _lp.parent.mkdir(parents=True, exist_ok=True)
        _tmp = _lp.with_suffix(".tmp")
        _tmp.write_text(json.dumps(launch, indent=2))
        os.replace(str(_tmp), str(_lp))
        print(f"[spike-actuator] launch-spike: {_lp} ({launch['n_implement']} items)")
    except Exception as exc:
        print(f"[spike-actuator] WARNING: could not write launch-spike.json: {exc}")

    print(f"[spike-actuator] {datetime.now(UTC).isoformat()}")
    print(f"[spike-actuator] report: {_report_path}")
    print(f"[spike-actuator] IMPLEMENT items: {len(items)}")
    print(f"[spike-actuator] spikes dir: {_spikes_dir}")
    print(f"[spike-actuator] dry_run={args.dry_run}  force={args.force}")

    if not items:
        print("[spike-actuator] No IMPLEMENT items — nothing to do.")
        _write_log([], 0, 0, 0, 0, log_path=_log_path)
        sys.exit(0)

    log_items: list[dict] = []
    n_created = n_skipped = n_errors = 0

    for item in items:
        title = item.get("title", "?")
        print(f"\n[spike-actuator] {title[:70]}")
        try:
            entry = process_item(item, args.dry_run, args.force)
            log_items.append(entry)
            if entry["status"] in ("created", "would-create"):
                n_created += 1
            else:
                n_skipped += 1
        except Exception as exc:
            print(f"  [ERROR] {exc}")
            log_items.append({"title": title, "status": "error", "reason": str(exc)})
            n_errors += 1

    print(f"\n[spike-actuator] Done: {n_created} created, {n_skipped} skipped, {n_errors} errors")

    if not args.dry_run:
        _write_log(log_items, len(items), n_created, n_skipped, n_errors, log_path=_log_path)


def _write_log(items: list, processed: int, created: int, skipped: int, errors: int,
               log_path=None) -> None:
    _path = log_path or LOG_PATH
    payload = {
        "run_at":                datetime.now(UTC).isoformat(),
        "items_processed":       processed,
        "stubs_created":         created,
        "tests_created":         sum(1 for i in items if i.get("test_path")),
        "skipped":               skipped,
        "errors":                errors,
        # SA-001: separate counts so the pipeline saturation check can read viable_stubs_created
        "viable_stubs_created":  sum(1 for i in items if i.get("status") in ("created", "would-create")),
        "governance_deferred":   sum(1 for i in items if i.get("status") == "governance-deferred"),
        "items":                 items,
    }
    tmp = _path.with_suffix(".tmp")
    tmp.write_text(json.dumps(payload, indent=2))
    os.replace(str(tmp), str(_path))


if __name__ == "__main__":
    main()
